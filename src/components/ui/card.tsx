  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn('rounded-card bg-card text-card-foreground', className)}
    {...props}
  />
));
Card.displayName = 'Card';

