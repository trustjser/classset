import * as React from 'react';
import { cn } from '@/lib/utils';

/**
 * 严格遵循 DESIGN.md 第 4 节：
 * 一级内容面板使用 20px 圆角 (rounded-card)，无静态投影，依靠表面色 (bg-surface) 与画布区分。
 */
